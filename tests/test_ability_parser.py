def page(**kw):
    return parse_ability_html("Nurinarim", FIXTURE,
                              ["Warframe_Abilities", "Narin", "Update_44"], **kw)


def test_detected_as_ability():
    assert page().is_ability


def test_sections_found_and_skipped_ones_dropped():
    p = page()
    assert list(p.sections) == ["Info", "Kit Interactions", "Bugs"]
    flat = "\n".join(l for s in p.sections.values() for l in s)
    assert "SHOULD NOT APPEAR" not in flat
    assert "Erfordert" not in flat


def test_nested_bullets_keep_hierarchy_and_bold():
    info = page().sections["Info"]
    assert info[0].startswith("- Once Narin has full Ice")
    assert "**25**" in info[0]
    assert info[1].startswith("  - Each slash")      # nested -> indented
    assert info[3].startswith("- During the sword dance")


def test_description_stats_intro_cost():
    p = page()
    assert p.description.startswith("Requires full Ice to cast")
    assert set(p.stats) >= {"Strength", "Duration", "Range", "Misc"}
    assert p.stats["Strength"][0].startswith("200 / 300 / 400 / 500")
    assert any("12,500" in v for v in p.stats["Strength"])
    assert p.stats["Duration"] == ["20s Maximum Duration"]
    assert "Update 44.0" in p.introduced and "2026-09-23" in p.introduced
    assert p.energy_cost == "25"


def test_image_fallback_from_html_returns_original_not_thumb():
    img = page().image_url
    assert img and "/thumb/" not in img and "Nurinarim" in img


def test_explicit_image_wins():
    assert page(image_url="https://x/y.png").image_url == "https://x/y.png"


def test_non_ability_page():
    p = parse_ability_html("Nova", "<div class='mw-parser-output'><p>hi</p></div>", ["Warframes"])
    assert not p.is_ability and not p.sections


def test_clean_text_strips_tokens():
    assert clean_text("massive <DT_FREEZE_COLOR> Cold , damage") == "massive Cold, damage"


def test_paginate_respects_limit_and_keeps_order():
    from wiki.ability import paginate
    lines = [f"- line {i} " + "x" * 90 for i in range(200)]
    pages = paginate(lines, limit=1000)
    assert all(len(p) <= 1000 for p in pages) and len(pages) > 1
    assert "\n".join(pages).split("\n") == lines


def test_paginate_splits_giant_line_without_spaces():
    from wiki.ability import paginate
    pages = paginate(["y" * 5000], limit=1000)
    assert all(len(p) <= 1000 for p in pages) and "".join(pages) == "y" * 5000


def test_paginate_empty():
    from wiki.ability import paginate
    assert paginate([]) == []


class _Resp:
    def __init__(self, status, body):
        self.status, self._b = status, body
    async def json(self):
        return self._b
    async def __aenter__(self):
        return self
    async def __aexit__(self, *a):
        return False


class _Sess:
    def __init__(self, status, body):
        self.r = _Resp(status, body)
    def get(self, url, params=None, headers=None):
        return self.r


def test_is_ability_title_three_states():
    import asyncio
    from wiki.ability import is_ability_title
    run = lambda c: asyncio.new_event_loop().run_until_complete(c)
    yes = {"query": {"pages": [{"title": "Nurinarim", "categories": [{"title": "Category:Warframe Abilities"}]}]}}
    no = {"query": {"pages": [{"title": "Serration"}]}}
    missing = {"query": {"pages": [{"title": "Zzz", "missing": True}]}}
    assert run(is_ability_title(_Sess(200, yes), "Nurinarim")) is True
    assert run(is_ability_title(_Sess(200, no), "Serration")) is False
    assert run(is_ability_title(_Sess(200, missing), "Zzz")) is None
    assert run(is_ability_title(_Sess(500, {}), "X")) is False
